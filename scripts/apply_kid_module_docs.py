def py_doc(text: str) -> str:
    return '"""' + text.strip() + '\n"""\n'


def js_doc(text: str) -> str:
    lines = ["/**", " * " + text.split("\n")[0]]
    for line in text.split("\n")[1:]:
        lines.append(" * " + line)
    lines.append(" */")
    return "\n".join(lines) + "\n"


def strip_leading_doc(content: str, is_py: bool) -> str:
    if is_py:
        m = re.match(r'^("""[\s\S]*?"""|\'\'\'[\s\S]*?\'\'\')\s*', content)
        if m:
            return content[m.end() :]
        return content
    m = re.match(r"^/\*\*[\s\S]*?\*/\s*", content)
    if m:
        return content[m.end() :]
    return content


def main():
    for rel, text in PY_DOCS.items():
        path = ROOT / rel
        body = strip_leading_doc(path.read_text(encoding="utf-8"), True)
        path.write_text(py_doc(text) + body, encoding="utf-8")
        print("py", rel)
    for rel, text in JS_DOCS.items():
        path = ROOT / rel
        body = strip_leading_doc(path.read_text(encoding="utf-8"), False)
        path.write_text(js_doc(text) + body, encoding="utf-8")
        print("js", rel)


if __name__ == "__main__":
    main()